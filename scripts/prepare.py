#!/usr/bin/env python3
"""Plan or explicitly generate frozen certificate sources in an isolated staging tree."""
from __future__ import annotations
import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import shutil
import subprocess
from common import digest, inside, read_json, select_paper
from generated import MANIFEST, manifest, output_status

def prepare(project: Path, execute=False, check=False) -> dict:
    data = manifest(project)
    if data is None:
        return {'plan_only':True,'generated_artifacts':'none','execution_started':False}
    status = output_status(project,data)
    record = {'plan_only':not execute,'execution_started':False,'outputs':status,
              'commands':data['commands'],'requirements':data.get('requirements',data.get('notes',[])),
              'manifest_sha256':digest(project/MANIFEST),
              'generation_validation':'not_run','lean_validation':'not_run'}
    if check:
        record['hash_check_passed'] = status['ready']
        return record
    if not execute:
        return record
    if status['mismatched']:
        raise ValueError('Refusing to overwrite changed generated outputs: '+', '.join(status['mismatched'][:5]))
    if status['ready']:
        record['generation_validation']='existing_outputs_match_frozen_hashes'
        return record
    stamp=datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%S%fZ')
    staging=inside(project,'.lake/generation/'+stamp)
    staging.mkdir(parents=True,exist_ok=False)
    record['execution_started']=True
    record['staging_directory']=str(staging)
    log=staging/'generation.log'
    receipt=staging/'result.json'
    try:
        for entry in data['inputs']:
            target=inside(staging,entry['path'])
            target.parent.mkdir(parents=True,exist_ok=True)
            shutil.copy2(inside(project,entry['path']),target)
        with log.open('w') as stream:
            for command in data['commands']:
                print('COMMAND: '+json.dumps(command),file=stream,flush=True)
                result=subprocess.run(command,cwd=staging,stdout=stream,stderr=subprocess.STDOUT)
                record['last_exit_code']=result.returncode
                if result.returncode:
                    raise ValueError('Generator exited with '+str(result.returncode)+'; inspect '+str(log))
        for entry in data['inputs']:
            if digest(inside(staging,entry['path'])) != entry['sha256']:
                raise ValueError('Generator changed a frozen source input: '+entry['path'])
        if digest(project/MANIFEST) != record['manifest_sha256']:
            raise ValueError('Generated artifact manifest changed during generation')
        # Check current source inputs as well as the complete staged output set.
        manifest(project)
        staged=output_status(staging,data)
        record['staged_outputs']=staged
        if not staged['ready']:
            raise ValueError('Generated bytes do not match the frozen snapshot; no outputs installed. See '+str(receipt))
        # Validate every destination before copying any output into the source tree.
        for entry in data['outputs']:
            destination=inside(project,entry['path'])
            if destination.exists() and (not destination.is_file() or digest(destination)!=entry['sha256']):
                raise ValueError('Destination changed during generation: '+entry['path'])
        for entry in data['outputs']:
            destination=inside(project,entry['path'])
            destination.parent.mkdir(parents=True,exist_ok=True)
            temporary=destination.with_name(destination.name+'.preparing')
            if temporary.exists():raise ValueError('Unexpected preparation temporary file: '+str(temporary))
            try:
                shutil.copyfile(inside(staging,entry['path']),temporary)
                if temporary.stat().st_size != entry['bytes'] or digest(temporary)!=entry['sha256']:
                    raise ValueError('Output changed while copying; refusing installation: '+entry['path'])
                os.replace(temporary,destination)
            finally:
                if temporary.exists():temporary.unlink()
        record['outputs']=output_status(project,data)
        if not record['outputs']['ready']:
            raise ValueError('Installed generated outputs changed before final validation')
        record['generation_validation']='all_outputs_match_frozen_hashes'
    except (OSError,ValueError,subprocess.SubprocessError) as error:
        record['error']=str(error)
        record['generation_validation']='failed'
        receipt.write_text(json.dumps(record,indent=2)+'\n')
        raise
    receipt.write_text(json.dumps(record,indent=2)+'\n')
    return record

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--paper',required=True)
    mode=parser.add_mutually_exclusive_group()
    mode.add_argument('--execute',action='store_true',help='Explicitly run candidate generation; may be expensive.')
    mode.add_argument('--check',action='store_true',help='Check existing outputs against frozen hashes without generation.')
    args=parser.parse_args()
    project,_=select_paper(args.paper)
    try:
        result=prepare(project,execute=args.execute,check=args.check)
        print(json.dumps(result,indent=2))
        if args.check and result.get('hash_check_passed') is False:return 1
        return 0
    except (OSError,ValueError,subprocess.SubprocessError) as error:
        parser.error(str(error))

if __name__=='__main__':raise SystemExit(main())
